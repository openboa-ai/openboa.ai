import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { exit } from "node:process"

const SOURCE_COMMIT = "e93f55cbfd90b668ef9d77875f71d8e53f7ceb4b"
const EXPECTED_SNAPSHOT_SHA256 =
  "63d0e9b046cedbd4ee062baac3f4972e2617c69ebdbd2c623c4bf9a4a8faa4b1"

const snapshotUrl = new URL(
  "../src/design-system/openboa.tokens.json",
  import.meta.url,
)
const cssUrl = new URL(
  "../src/design-system/generated/openboa-tokens.css",
  import.meta.url,
)
const valuesUrl = new URL(
  "../src/design-system/generated/openboa-token-values.ts",
  import.meta.url,
)

const snapshotSource = await readFile(snapshotUrl, "utf8")
const snapshotSha256 = createHash("sha256")
  .update(snapshotSource)
  .digest("hex")

if (snapshotSha256 !== EXPECTED_SNAPSHOT_SHA256) {
  throw new Error(
    `OpenBoa token snapshot drifted: expected ${EXPECTED_SNAPSHOT_SHA256}, received ${snapshotSha256}`,
  )
}

const tokens = JSON.parse(snapshotSource)

function nodeAt(path) {
  const value = path.split(".").reduce((current, segment) => {
    if (current && Object.hasOwn(current, segment)) return current[segment]
    throw new Error(`Missing OpenBoa token: ${path}`)
  }, tokens)

  return value
}

function resolveValue(value, stack = []) {
  if (typeof value === "string") {
    const alias = value.match(/^\{([^}]+)\}$/)
    if (!alias) return value
    const path = alias[1]
    if (stack.includes(path)) {
      throw new Error(`Circular OpenBoa token alias: ${[...stack, path].join(" -> ")}`)
    }
    return resolveToken(path, [...stack, path])
  }

  if (Array.isArray(value)) {
    return value.map((item) => resolveValue(item, stack))
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, resolveValue(item, stack)]),
    )
  }

  return value
}

function resolveToken(path, stack = [path]) {
  const node = nodeAt(path)
  if (!node || !Object.hasOwn(node, "$value")) {
    throw new Error(`OpenBoa path is not a token: ${path}`)
  }
  return resolveValue(node.$value, stack)
}

function color(path) {
  const value = resolveToken(path)
  if (!value || value.colorSpace !== "srgb" || !value.hex) {
    throw new Error(`OpenBoa token is not an sRGB color: ${path}`)
  }
  return {
    hex: value.hex,
    rgb: value.components.map((component) => Number(component.toFixed(8))),
  }
}

function dimension(path) {
  const value = resolveToken(path)
  return `${value.value}${value.unit}`
}

function duration(path) {
  const value = resolveToken(path)
  return `${value.value}${value.unit}`
}

function easing(path) {
  return `cubic-bezier(${resolveToken(path).join(", ")})`
}

function typography(path) {
  const node = nodeAt(path)
  const value = resolveToken(path)
  const extension = node.$extensions?.["org.openboa"] ?? {}
  return {
    family: value.fontFamily.map((family) => (
      family.includes(" ") ? `"${family}"` : family
    )).join(", "),
    size: `${value.fontSize.value}${value.fontSize.unit}`,
    lineHeight: value.lineHeight,
    weight: value.fontWeight,
    width: extension.axes?.wdth ?? 100,
    tracking: `${extension["tracking-em"] ?? 0}em`,
  }
}

const colorPaths = {
  canvas: "sys.color.light.background.canvas",
  surface: "sys.color.light.background.surface",
  textExpression: "sys.color.light.text.expression",
  textPrimary: "sys.color.light.text.primary",
  textSecondary: "sys.color.light.text.secondary",
  textMuted: "sys.color.light.text.muted",
  textAccent: "sys.color.light.text.accent",
  focusRing: "sys.color.light.focus.ring",
  focusOffset: "sys.color.light.focus.offset",
  selectionFill: "sys.color.light.selection.fill",
  selectionContent: "sys.color.light.selection.content",
  terracotta50: "ref.color.palette.terracotta.50",
  terracotta100: "ref.color.palette.terracotta.100",
  terracotta200: "ref.color.palette.terracotta.200",
  terracotta300: "ref.color.palette.terracotta.300",
  terracotta400: "ref.color.palette.terracotta.400",
  terracotta500: "ref.color.palette.terracotta.500",
}

const typographyPaths = {
  hero: "sys.type.expression.display-03",
  heroMobile: "sys.type.expression.title-02",
  body: "sys.type.product.body-02",
  label: "sys.type.support.label-01",
  caption: "sys.type.support.caption-02",
}

const colors = Object.fromEntries(
  Object.entries(colorPaths).map(([name, path]) => [name, color(path)]),
)
const type = Object.fromEntries(
  Object.entries(typographyPaths).map(([name, path]) => [name, typography(path)]),
)

const cssName = (name) => name
  .replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
  .replace(/([a-z])(\d)/g, "$1-$2")
const cssLines = [
  "/* This file is generated by scripts/generate-openboa-tokens.mjs. */",
  `/* Source: openboa-brand-system@${SOURCE_COMMIT} */`,
  ":root {",
  ...Object.entries(colors).map(
    ([name, value]) => `  --ob-color-${cssName(name)}: ${value.hex};`,
  ),
  ...Object.entries(type).flatMap(([name, value]) => [
    `  --ob-type-${cssName(name)}-family: ${value.family};`,
    `  --ob-type-${cssName(name)}-size: ${value.size};`,
    `  --ob-type-${cssName(name)}-line-height: ${value.lineHeight};`,
    `  --ob-type-${cssName(name)}-weight: ${value.weight};`,
    `  --ob-type-${cssName(name)}-width: ${value.width};`,
    `  --ob-type-${cssName(name)}-tracking: ${value.tracking};`,
  ]),
  `  --ob-motion-duration-80: ${duration("ref.motion.duration.80")};`,
  `  --ob-motion-duration-160: ${duration("ref.motion.duration.160")};`,
  `  --ob-motion-duration-220: ${duration("ref.motion.duration.220")};`,
  `  --ob-motion-duration-320: ${duration("ref.motion.duration.320")};`,
  `  --ob-motion-duration-480: ${duration("ref.motion.duration.480")};`,
  `  --ob-motion-easing-standard: ${easing("ref.motion.easing.standard")};`,
  `  --ob-motion-easing-enter: ${easing("ref.motion.easing.enter")};`,
  `  --ob-motion-easing-exit: ${easing("ref.motion.easing.exit")};`,
  ...[4, 8, 12, 16, 20, 24, 32, 40, 48, 64, 80, 96].map(
    (step) => `  --ob-space-${step}: ${dimension(`ref.space.${step}`)};`,
  ),
  `  --ob-icon-size: ${dimension("ref.icon.size.16")};`,
  `  --ob-breakpoint-mobile: ${dimension("ref.breakpoint.768")};`,
  "}",
  "",
].join("\n")

const valuesSource = `${[
  "// This file is generated by scripts/generate-openboa-tokens.mjs.",
  `// Source: openboa-brand-system@${SOURCE_COMMIT}`,
  "",
  `export const OPENBOA_TOKEN_SOURCE = ${JSON.stringify({
    repository: "openboa-ai/openboa-brand-system",
    commit: SOURCE_COMMIT,
    snapshotSha256,
  }, null, 2)} as const`,
  "",
  `export const OPENBOA_COLORS = ${JSON.stringify(colors, null, 2)} as const`,
  "",
  `export const OPENBOA_TYPOGRAPHY = ${JSON.stringify(type, null, 2)} as const`,
].join("\n")}\n`

const outputs = [
  [cssUrl, cssLines],
  [valuesUrl, valuesSource],
]

if (process.argv.includes("--check")) {
  let drifted = false
  for (const [url, expected] of outputs) {
    let actual = ""
    try {
      actual = await readFile(url, "utf8")
    } catch {
      drifted = true
      console.error(`Missing generated token output: ${url.pathname}`)
      continue
    }
    if (actual !== expected) {
      drifted = true
      console.error(`Generated token output drifted: ${url.pathname}`)
    }
  }
  if (drifted) exit(1)
  console.log(`OpenBoa token outputs are current (${snapshotSha256.slice(0, 12)}).`)
} else {
  for (const [url, output] of outputs) {
    await writeFile(url, output)
  }
  console.log(`Generated OpenBoa token outputs (${snapshotSha256.slice(0, 12)}).`)
}
