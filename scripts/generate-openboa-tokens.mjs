import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { exit } from "node:process"

const SOURCE_PACKAGE = "@openboa/yogurt@0.2.0-local.1"
const SOURCE_COMMIT = "8c0de34ce2bcf795c44e28c406a6070fd1a4eaca"
const EXPECTED_SNAPSHOT_SHA256 =
  "f42926bd163c21e0e8fc74f9924dfbae88ce23e5aee3edff843cd06a25564993"

const snapshotUrl = new URL(
  "../src/design-system/openboa.tokens.json",
  import.meta.url,
)
const cssUrl = new URL(
  "../src/design-system/generated/openboa-tokens.css",
  import.meta.url,
)
const valuesUrl = new URL(
  "../src/design-system/generated/openboa-token-values.ts",
  import.meta.url,
)

const snapshotSource = await readFile(snapshotUrl, "utf8")
const snapshotSha256 = createHash("sha256")
  .update(snapshotSource)
  .digest("hex")

if (snapshotSha256 !== EXPECTED_SNAPSHOT_SHA256) {
  throw new Error(
    `OpenBoa Yogurt token snapshot drifted: expected ${EXPECTED_SNAPSHOT_SHA256}, received ${snapshotSha256}`,
  )
}

const brand = JSON.parse(snapshotSource)

function hex(family, step) {
  const value = brand?.color?.[family]?.[String(step)]
  if (typeof value !== "string" || !/^#[0-9A-F]{6}$/i.test(value)) {
    throw new Error(`Missing Yogurt color token: color.${family}.${step}`)
  }
  return value
}

const colors = {
  canvasLight: hex("neutral", 50),
  surfaceLight: hex("neutral", 100),
  canvasDark: hex("neutral", 950),
  surfaceDark: hex("neutral", 900),
  inkLight: hex("neutral", 950),
  inkDark: hex("neutral", 100),
  mutedLight: hex("neutral", 600),
  mutedDark: hex("neutral", 300),
  brandInkLight: hex("slate", 700),
  brandInkDark: hex("slate", 300),
  brandHoverLight: hex("slate", 800),
  brandSoftLight: hex("slate", 50),
  brandSoftDark: hex("slate", 900),
  slate200: hex("slate", 200),
  slate500: hex("slate", 500),
  slate950: hex("slate", 950),
}

const typography = {
  family: brand.type.family,
  monoFamily: brand.type.monoFamily,
  roleWeight: brand.type.roleWeight,
  tracking: brand.type.tracking,
}

const cssName = (name) =>
  name
    .replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
    .replace(/([a-z])(\d)/g, "$1-$2")

const cssLines = [
  "/* This file is generated by scripts/generate-openboa-tokens.mjs. */",
  `/* Source: ${SOURCE_PACKAGE} (${SOURCE_COMMIT}) */`,
  ":root {",
  ...Object.entries(colors).map(
    ([name, value]) => `  --ob-color-${cssName(name)}: ${value};`,
  ),
  `  --ob-font-sans: "${typography.family}", system-ui, -apple-system, sans-serif;`,
  `  --ob-font-mono: ${typography.monoFamily};`,
  `  --ob-radius-control: ${brand.radius.control}px;`,
  `  --ob-radius-panel: ${brand.radius.panel}px;`,
  `  --ob-radius-card: ${brand.radius.card}px;`,
  `  --ob-radius-round: ${brand.radius.round}px;`,
  "}",
  "",
].join("\n")

const valuesSource = `${[
  "// This file is generated by scripts/generate-openboa-tokens.mjs.",
  `// Source: ${SOURCE_PACKAGE} (${SOURCE_COMMIT})`,
  "",
  `export const OPENBOA_TOKEN_SOURCE = ${JSON.stringify(
    {
      package: SOURCE_PACKAGE,
      commit: SOURCE_COMMIT,
      snapshotSha256,
    },
    null,
    2,
  )} as const`,
  "",
  `export const OPENBOA_COLORS = ${JSON.stringify(colors, null, 2)} as const`,
  "",
  `export const OPENBOA_TYPOGRAPHY = ${JSON.stringify(typography, null, 2)} as const`,
].join("\n")}\n`

const outputs = [
  [cssUrl, cssLines],
  [valuesUrl, valuesSource],
]

if (process.argv.includes("--check")) {
  let drifted = false
  for (const [url, expected] of outputs) {
    let actual = ""
    try {
      actual = await readFile(url, "utf8")
    } catch {
      drifted = true
      console.error(`Missing generated token output: ${url.pathname}`)
      continue
    }
    if (actual !== expected) {
      drifted = true
      console.error(`Generated token output drifted: ${url.pathname}`)
    }
  }
  if (drifted) exit(1)
  console.log(`OpenBoa Yogurt token outputs are current (${snapshotSha256.slice(0, 12)}).`)
} else {
  for (const [url, output] of outputs) {
    await writeFile(url, output)
  }
  console.log(`Generated OpenBoa Yogurt token outputs (${snapshotSha256.slice(0, 12)}).`)
}
